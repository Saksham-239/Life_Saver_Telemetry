#include <stdio.h>
#include <stdlib.h>
#include <stdbool.h>
#include <assert.h>
#include "buttons.h"

uint32_t g_sim_gpio_in = 0xFFFFFFFFu;
uint32_t g_sim_now_ms = 0;

static void simulate_gpio_press(button_id_t btn) {
    g_sim_gpio_in &= ~(1u << (7 + btn));
}

static void simulate_gpio_release(button_id_t btn) {
    g_sim_gpio_in |= (1u << (7 + btn));
}

static bool simulate_click(button_id_t btn, uint32_t hold_ms, button_event_t *ev_out) {
    bool got_ev = false;
    simulate_gpio_press(btn);
    for (uint32_t elapsed = 0; elapsed < hold_ms; elapsed += 10) {
        g_sim_now_ms += 10;
        if (buttons_tick(g_sim_now_ms, ev_out)) got_ev = true;
    }
    simulate_gpio_release(btn);
    for (uint32_t elapsed = 0; elapsed < 40; elapsed += 10) {
        g_sim_now_ms += 10;
        if (buttons_tick(g_sim_now_ms, ev_out)) got_ev = true;
    }
    return got_ev;
}

static bool advance_idle(uint32_t ms, button_event_t *ev_out) {
    bool got_ev = false;
    for (uint32_t elapsed = 0; elapsed < ms; elapsed += 10) {
        g_sim_now_ms += 10;
        if (buttons_tick(g_sim_now_ms, ev_out)) got_ev = true;
    }
    return got_ev;
}

int main(void) {
    printf("=== TEST: Button Tick FSM & Hold/Double-Press Semantics (MISS-01 Verification) ===\n");

    buttons_init();
    button_event_t ev;

    /* Subtest 1: Double-press on BUTTON_BACKUP does not trigger fall cancel */
    printf("--- Subtest 1: Double-Press on BUTTON_BACKUP vs BUTTON_COMPLETE ---\n");
    g_sim_now_ms = 1000;
    simulate_click(BUTTON_BACKUP, 60, &ev);
    advance_idle(100, &ev);
    bool had_event = simulate_click(BUTTON_BACKUP, 60, &ev);

    if (had_event) {
        printf("Event on BACKUP double-press: btn=%d, type=%d\n", ev.btn, ev.type);
    }
    bool complete_double = button_double_press_detected();
    printf("button_double_press_detected (for cancel): %d\n", complete_double);
    if (complete_double) {
        fprintf(stderr, "FAIL: Double-press on BUTTON_BACKUP inappropriately triggered fall cancel flag!\n");
        return 1;
    }
    printf("  [PASS] Double-press on BACKUP correctly ignored for fall-cancel.\n");

    /* Subtest 2: Double-press on BUTTON_COMPLETE triggers fall cancel */
    printf("--- Subtest 2: Double-Press on BUTTON_COMPLETE ---\n");
    advance_idle(500, &ev);
    simulate_click(BUTTON_COMPLETE, 60, &ev);
    advance_idle(100, &ev);
    had_event = simulate_click(BUTTON_COMPLETE, 60, &ev);

    if (!had_event || ev.btn != BUTTON_COMPLETE || ev.type != BTN_EV_DOUBLE_PRESS) {
        fprintf(stderr, "FAIL: Double-press on BUTTON_COMPLETE not generated by FSM! (had_ev=%d, btn=%d, type=%d)\n",
                had_event, ev.btn, ev.type);
        return 1;
    }
    if (!button_double_press_detected()) {
        fprintf(stderr, "FAIL: button_double_press_detected() returned false for BUTTON_COMPLETE!\n");
        return 1;
    }
    printf("  [PASS] Double-press on BUTTON_COMPLETE generates CANCEL.\n");

    /* Subtest 3: Long-press on BUTTON_COMPLETE (>= 3000 ms) */
    printf("--- Subtest 3: Long-Press on BUTTON_COMPLETE (Clear Emergency) ---\n");
    advance_idle(500, &ev);
    simulate_gpio_press(BUTTON_COMPLETE);
    bool long_fired = false;
    for (uint32_t t = 0; t < 2900; t += 10) {
        g_sim_now_ms += 10;
        if (buttons_tick(g_sim_now_ms, &ev) && ev.type == BTN_EV_LONG_PRESS) long_fired = true;
    }
    if (long_fired) {
        fprintf(stderr, "FAIL: Long-press fired prematurely (< 3000 ms)!\n");
        return 1;
    }

    for (uint32_t t = 0; t < 200; t += 10) {
        g_sim_now_ms += 10;
        if (buttons_tick(g_sim_now_ms, &ev) && ev.type == BTN_EV_LONG_PRESS && ev.btn == BUTTON_COMPLETE) {
            long_fired = true;
        }
    }
    if (!long_fired) {
        fprintf(stderr, "FAIL: Long-press on BUTTON_COMPLETE did not fire at >= 3000 ms!\n");
        return 1;
    }
    simulate_gpio_release(BUTTON_COMPLETE);
    advance_idle(50, &ev);
    printf("  [PASS] Long-press on BUTTON_COMPLETE fired at >= 3000 ms.\n");

    /* Subtest 4: Short press on BUTTON_ENEMY */
    printf("--- Subtest 4: Short Press on BUTTON_ENEMY ---\n");
    advance_idle(500, &ev);
    simulate_click(BUTTON_ENEMY, 60, &ev);
    /* Double press window is 400 ms: advance idle by 450 ms */
    had_event = advance_idle(450, &ev);
    if (!had_event || ev.btn != BUTTON_ENEMY || ev.type != BTN_EV_SHORT_PRESS) {
        fprintf(stderr, "FAIL: Short press on BUTTON_ENEMY not emitted after double window! (had_ev=%d, btn=%d, type=%d)\n",
                had_event, ev.btn, ev.type);
        return 1;
    }
    printf("  [PASS] Short press on BUTTON_ENEMY correctly emitted.\n");

    /* Subtest 5: Noise glitch rejection (< 20 ms) */
    printf("--- Subtest 5: Noise Glitch Rejection (< 20 ms) ---\n");
    advance_idle(500, &ev);
    simulate_gpio_press(BUTTON_MEDICAL);
    g_sim_now_ms += 10; /* Only 10 ms pulse < 20 ms debounce */
    buttons_tick(g_sim_now_ms, &ev);
    simulate_gpio_release(BUTTON_MEDICAL);
    had_event = advance_idle(500, &ev);
    if (had_event) {
        fprintf(stderr, "FAIL: 10 ms noise glitch produced a button event!\n");
        return 1;
    }
    printf("  [PASS] 10 ms glitch correctly rejected by debounce.\n");

    printf("PASS: All button FSM tests passed.\n");
    return 0;
}
